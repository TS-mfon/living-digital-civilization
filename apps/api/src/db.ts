export async function seedGenesis(): Promise<void> {
  const exists = await first<{ id: string }>('SELECT id FROM organizations WHERE id=$1', [GENESIS_ID]);
  if (!exists) {
    await execute(`INSERT INTO organizations(id,family_id,parent_id,previous_id,name,organization_type,purpose,constitution,generation,version,resource_units,status,address,created_at)
      VALUES($1,$2,NULL,NULL,$3,$4,$5,$6,0,1,1000000,'active',NULL,$7) ON CONFLICT(id) DO NOTHING`, [
      GENESIS_ID,
      keccak256(concatHex([stringToHex('FAMILY'), GENESIS_ID])),
      'Living Civilization', 'civilization',
      'Create and evolve useful institutions within an immutable constitutional core.',
      'Immutable constitutional core; bounded authority; transparent lineage; resource accounting.', now(),
    ]);
  }
}
await seedGenesis();

