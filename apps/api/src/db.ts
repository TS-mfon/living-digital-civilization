export async function agentForApiKey(digest: string): Promise<{ id: string; name: string; digest: string } | undefined> {
  return first('SELECT agents.id,agents.name,api_keys.digest FROM api_keys JOIN agents ON agents.id=api_keys.agent_id WHERE api_keys.digest=$1 AND api_keys.revoked_at IS NULL', [digest]);
}
export async function revokeApiKey(agentId: string, keyId: string): Promise<boolean> {
  const result = await execute('UPDATE api_keys SET revoked_at=$1 WHERE id=$2 AND agent_id=$3 AND revoked_at IS NULL', [now(), keyId, agentId]);
  return result.changes === 1;
}

