    'SELECT id,action,status,evaluation,genlayer_tx as "genlayerTx",base_tx as "baseTx",created_at as "createdAt" FROM proposals WHERE organization_id=$1 OR parent_id=$1 ORDER BY created_at DESC LIMIT 10',
